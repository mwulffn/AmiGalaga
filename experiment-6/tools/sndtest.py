"""Test script for the Amiga sound driver, and the check of its log.

    python3 sndtest.py script build/sndtest_script.i     write the script
    python3 sndtest.py ticks                              print how many ticks it needs
    python3 sndtest.py check galaga.zip results           compare a results file

The script requests every sound in turn, then piles sounds on top of each
other. A -DSNDTEST build applies it tick by tick and logs what the driver
sends to Paula's three tone channels; `check` replays the same script
through sound/native.py (identical to the arcade) and compares.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "sound"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import galaga_sound as S  # noqa: E402
import native as N  # noqa: E402
from make_sound_data import paula_entry  # noqa: E402

S_DIR, S_BANG = 71, 72  # offsets in snd_state
SCREEN = 42 * 4 * 288


def script() -> list[tuple[int, int, int]]:
    ev, t = [], 10
    for sound in S.SOUNDS:
        if sound in S.HELD:
            ev += [(t, sound, 1), (t + 150, sound, 0)]
            if sound == 0:
                ev += [(t, S_DIR, 0x01), (t + 60, S_DIR, 0xFF), (t + 120, S_DIR, 0x01)]
        else:
            ev.append((t, sound, 3 if sound in (0x08, 0x0A, 0x0C) else 1))
        t += 200
    t += 900  # let the last tune finish, then a pile-up
    ev += [(t, 0x0B, 1), (t, 0x00, 1)]
    ev += [(t + 256 * k, S_DIR, 0x01 if k % 2 else 0xFF) for k in range(5)]  # as often as the game does
    for k in range(60):
        ev.append((t + 13 * k, 0x0F, 1))
        if k % 3 == 0:
            ev.append((t + 13 * k + 5, 0x03 if k % 2 else 0x02, 1))
        if k % 7 == 0:
            ev.append((t + 13 * k + 2, 0x13, 1))
        if k % 11 == 0:
            ev.append((t + 13 * k + 7, 0x04 if k % 2 else 0x01, 1))
    ev += [(t + 100, S_BANG, 1), (t + 400, 0x05, 1), (t + 500, 0x06, 1), (t + 650, 0x05, 0), (t + 700, 0x06, 0)]
    return sorted(ev, key=lambda e: e[0])


def ticks() -> int:
    return script()[-1][0] + 240  # stop before the pulse runs longer than it does in the game


def main() -> None:
    if sys.argv[1] == "ticks":
        print(ticks())
    elif sys.argv[1] == "script":
        lines = ["; generated by tools/sndtest.py: tick, offset in snd_state, value"]
        # a sound's request byte is at twice its number
        lines += [f"\tdc.w\t{t}\n\tdc.b\t{off * 2 if off < 32 else off},{val}" for t, off, val in script()]
        Path(sys.argv[2]).write_text("\n".join(lines) + "\n\tdc.w\t$ffff\n")
    else:
        rom = S.Rom(sys.argv[2])
        log = Path(sys.argv[3]).read_bytes()[16 + SCREEN :]
        n, events, bad, first = N.Native(rom), script(), 0, None
        total = min(ticks(), len(log) // 12)
        for t in range(total):
            for _, off, val in (e for e in events if e[0] == t):
                if off == S_DIR:
                    n.direction = val
                elif off < 32:
                    n.req[off] = val
            n.tick()
            want = b"".join(paula_entry(f).to_bytes(2, "big") for f in n.freq)
            want += bytes(v & 15 for v in n.vol) + bytes(w & 7 for w in n.wave)
            got = log[t * 12 : t * 12 + 12]
            if got != want:
                bad += 1
                first = first or (t, got.hex(), want.hex())
        print(f"sound driver log: {total} ticks, {total - bad} identical to the arcade model, {bad} different")
        if first:
            print("  first difference at tick %d: Amiga %s, model %s" % first)


if __name__ == "__main__":
    main()
